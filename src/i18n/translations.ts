export const verificationLabel = (status: VerificationStatus, lang: ResolvedLanguage): string => {
  const map: Record<VerificationStatus, { id: string; en: string }> = {
    verified: { id: 'Terverifikasi', en: 'Verified' },
    likely: { id: 'Kemungkinan', en: 'Likely' },
    unverified: { id: 'Belum terverifikasi', en: 'Unverified' },
    needs_testing: { id: 'Perlu pengujian', en: 'Needs testing' },
    not_feasible: { id: 'Belum memungkinkan saat ini', en: 'Not feasible currently' },
  };
  return map[status][lang];
};

